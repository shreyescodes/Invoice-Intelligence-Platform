"""Measure field-level extraction accuracy on real-world invoices.

    uv run python -m benchmarks.realworld.run            # fetch (cached), score, print a summary
    uv run python -m benchmarks.realworld.run --write    # also update RESULTS.md and results.json
    uv run python -m benchmarks.realworld.run --details  # per-document misses (dev split only)

The text-layer parser is scored with embedded e-invoice XML switched off: for the ZUGFeRD corpus the
XML *is* the ground truth, so reading it would be circular.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from datetime import UTC, datetime
from decimal import Decimal

from rapidfuzz import fuzz

from app.services.extraction.base import ExtractionResult
from app.services.extraction.pdf_text import PdfTextExtractor
from app.services.vendors import normalize_name, normalize_tax_id
from benchmarks.realworld.datasets import HERE, Document, fetch, load
from benchmarks.realworld.truth import Truth, load_truth

FIELDS = (
    "invoice_number",
    "invoice_date",
    "total_amount",
    "subtotal",
    "tax_amount",
    "currency",
    "vendor_name",
    "vendor_tax_id",
    "due_date",
    "po_number",
)
CORE = ("invoice_number", "invoice_date", "total_amount")


def _key(value: object) -> str:
    return re.sub(r"[^A-Z0-9]", "", str(value).upper())


def matches(name: str, got: object, expected: object) -> bool:
    if got is None:
        return False
    if name in ("total_amount", "subtotal", "tax_amount"):
        return abs(Decimal(str(got)) - Decimal(str(expected))) <= Decimal("0.01")
    if name in ("invoice_number", "po_number"):
        return _key(got) == _key(expected) and bool(_key(got))
    if name == "vendor_tax_id":
        return normalize_tax_id(str(got)) == normalize_tax_id(str(expected))
    if name == "vendor_name":
        a, b = normalize_name(str(got)), normalize_name(str(expected))
        return bool(a) and (fuzz.token_set_ratio(a, b) >= 85 or a in b or b in a)
    return bool(got == expected)


@dataclass(slots=True)
class Score:
    document: Document
    truth: Truth
    result: ExtractionResult | None
    error: str | None = None

    def field_ok(self, name: str) -> bool | None:
        if name not in self.truth.values:
            return None
        got = getattr(self.result, name) if self.result else None
        expected = [self.truth.values[name], *self.truth.alternatives.get(name, [])]
        return any(matches(name, got, e) for e in expected)

    @property
    def core_ok(self) -> bool:
        return all(self.field_ok(f) in (True, None) for f in CORE)


def evaluate(documents: list[Document]) -> list[Score]:
    extractor = PdfTextExtractor(read_embedded=False)
    scores: list[Score] = []
    for document in documents:
        truth = load_truth(document)
        if truth is None:
            continue
        try:
            result = extractor.extract(document.path.read_bytes(), "application/pdf")
            scores.append(Score(document, truth, result))
        except Exception as exc:
            scores.append(Score(document, truth, None, error=f"{type(exc).__name__}: {exc}"))
    return scores


def summarise(scores: list[Score]) -> dict[str, object]:
    out: dict[str, object] = {"documents": len(scores)}
    fields: dict[str, dict[str, float]] = {}
    for name in FIELDS:
        judged = [s.field_ok(name) for s in scores]
        present = [j for j in judged if j is not None]
        if present:
            fields[name] = {"accuracy": round(sum(present) / len(present), 3), "n": len(present)}
    out["fields"] = fields
    out["core_all_correct"] = round(sum(s.core_ok for s in scores) / max(len(scores), 1), 3)
    return out


def markdown(results: dict[str, dict[str, object]], producers: dict[str, dict[str, object]]) -> str:
    splits = [s for s in ("dev", "test") if s in results]
    lines = [
        "# Extraction benchmark on real-world invoices",
        "",
        f"Generated by `python -m benchmarks.realworld.run --write` on {datetime.now(UTC):%Y-%m-%d}. Field-level "
        "accuracy of the text-layer extractor (embedded e-invoice XML disabled). Sources and licences are in "
        "[README.md](README.md).",
        "",
        "| Field | " + " | ".join(f"{s} accuracy (n)" for s in splits) + " |",
        "|---|" + "---|" * len(splits),
    ]
    for name in FIELDS:
        cells = []
        for split in splits:
            stats = results[split]["fields"].get(name)  # type: ignore[union-attr]
            cells.append(f"{stats['accuracy']:.0%} ({stats['n']})" if stats else "-")
        lines.append(f"| `{name}` | " + " | ".join(cells) + " |")
    lines.append(
        "| **invoice no. + date + total all correct** | "
        + " | ".join(f"**{results[s]['core_all_correct']:.0%}** ({results[s]['documents']})" for s in splits)
        + " |"
    )
    lines += [
        "",
        "## By producer",
        "",
        "| Producer | Split | Documents | Core fields all correct |",
        "|---|---|---|---|",
    ]
    for producer, stats in sorted(producers.items()):
        lines.append(f"| {producer} | {stats['split']} | {stats['documents']} | {stats['core_all_correct']:.0%} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="update RESULTS.md and results.json")
    parser.add_argument("--details", action="store_true", help="print misses for dev documents")
    parser.add_argument("--split", choices=["dev", "test", "all"], default="all")
    parser.add_argument(
        "--fail-under",
        type=float,
        default=None,
        metavar="RATE",
        help="exit non-zero if the held-out core-field rate drops below RATE (CI regression gate)",
    )
    args = parser.parse_args(argv)

    documents = load()
    fetch(documents)
    scores = evaluate(documents)

    results: dict[str, dict[str, object]] = {}
    for split in ("dev", "test"):
        if args.split in (split, "all"):
            results[split] = summarise([s for s in scores if s.document.split == split])
    by_producer: dict[str, list[Score]] = defaultdict(list)
    for s in scores:
        by_producer[
            f"{s.document.corpus}/{s.document.producer}" if s.document.corpus == "zugferd" else "invoice2data"
        ].append(s)
    producers = {name: {**summarise(group), "split": group[0].document.split} for name, group in by_producer.items()}

    report = markdown(results, producers)
    sys.stdout.write(report)
    if args.details:
        for s in scores:
            if s.document.split != "dev":
                continue  # never inspect held-out documents while tuning
            misses = [f for f in FIELDS if s.field_ok(f) is False]
            if misses or s.error:
                got = {f: getattr(s.result, f, None) for f in misses} if s.result else {}
                want = {f: s.truth.values[f] for f in misses}
                print(f"\n{s.document.id} ({s.document.producer}) {s.error or ''}\n  want {want}\n  got  {got}")
    if args.write:
        (HERE / "RESULTS.md").write_text(report, encoding="utf-8")
        payload = {"results": results, "producers": producers}
        (HERE / "results.json").write_text(json.dumps(payload, indent=2, default=str) + "\n", encoding="utf-8")
    if args.fail_under is not None and "test" in results:
        achieved = float(results["test"]["core_all_correct"])  # type: ignore[arg-type]
        if achieved < args.fail_under:
            print(f"\nHeld-out core-field rate {achieved:.0%} is below the {args.fail_under:.0%} gate", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
