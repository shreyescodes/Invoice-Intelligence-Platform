import { ArrowUp, Code2, Database, ShieldCheck, Sparkles } from "lucide-react";
import { useState, type FormEvent } from "react";

import { ResultChart } from "@/components/charts/ResultChart";
import { ToneBadge } from "@/components/ui/Badge";
import { Button } from "@/components/ui/Button";
import { Card, PageHeader } from "@/components/ui/Card";
import { Callout } from "@/components/ui/Feedback";
import { ApiError, type AskResult } from "@/lib/api";
import { formatMoney, humanize } from "@/lib/format";
import { useAsk, useMeta, useSuggestions } from "@/lib/queries";

const MONEY_COLUMN = /spend|amount|total|price|value/i;

function Cell({ column, value }: { column: string; value: unknown }) {
  if (value === null || value === undefined) return <span className="text-ink-3">—</span>;
  if (typeof value === "number") {
    return <>{MONEY_COLUMN.test(column) ? formatMoney(value) : value.toLocaleString("en-IN")}</>;
  }
  return <>{String(value)}</>;
}

function Answer({ result }: { result: AskResult }) {
  const [showSql, setShowSql] = useState(false);
  const numeric = result.columns.map((_, i) => result.rows.every((r) => typeof r[i] === "number" || r[i] === null));
  return (
    <Card>
      <div className="border-b border-line px-5 py-4">
        <div className="flex flex-wrap items-center gap-2">
          <h2 className="text-[15px] font-semibold text-ink">{result.question}</h2>
          {result.source === "catalog" ? (
            <ToneBadge tone="neutral" icon={Database}>
              Curated query
            </ToneBadge>
          ) : (
            <ToneBadge tone="info" icon={Sparkles}>
              Generated by {result.model}
            </ToneBadge>
          )}
        </div>
        <p className="mt-1.5 text-sm text-ink-2">{result.answer}</p>
      </div>
      <div className="grid gap-6 px-5 py-4 lg:grid-cols-[minmax(0,1fr)_minmax(0,1fr)]">
        {result.chart !== "table" && result.rows.length > 1 && (
          <div className="min-w-0">
            <ResultChart columns={result.columns} rows={result.rows} kind={result.chart} />
          </div>
        )}
        <div className={result.chart === "table" || result.rows.length <= 1 ? "lg:col-span-2" : "min-w-0"}>
          <div className="max-h-80 overflow-auto rounded-lg border border-line">
            <table className="w-full text-left text-[13px]">
              <thead className="sticky top-0 bg-surface-2 text-[12px] text-ink-3">
                <tr>
                  {result.columns.map((column, i) => (
                    <th key={column} className={`px-3 py-2 font-medium ${numeric[i] ? "text-right" : ""}`}>
                      {humanize(column)}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody className="tabular divide-y divide-line">
                {result.rows.map((row, r) => (
                  <tr key={r}>
                    {row.map((value, c) => (
                      <td key={c} className={`px-3 py-2 ${numeric[c] ? "text-right text-ink" : "text-ink-2"}`}>
                        <Cell column={result.columns[c] ?? ""} value={value} />
                      </td>
                    ))}
                  </tr>
                ))}
                {result.rows.length === 0 && (
                  <tr>
                    <td colSpan={result.columns.length} className="px-3 py-4 text-ink-3">
                      No rows.
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>
          {result.truncated && <p className="mt-2 text-[12px] text-ink-3">Showing the first {result.rows.length} rows.</p>}
        </div>
      </div>
      <div className="border-t border-line px-5 py-3">
        <button
          type="button"
          onClick={() => setShowSql((v) => !v)}
          className="inline-flex items-center gap-1.5 text-[13px] font-medium text-ink-2 hover:text-ink"
          aria-expanded={showSql}
        >
          <Code2 className="size-4" /> {showSql ? "Hide SQL" : "Show SQL"}
        </button>
        {showSql && (
          <pre className="mt-2 overflow-x-auto rounded-lg bg-surface-2 p-3 font-mono text-[12px] leading-5 whitespace-pre-wrap text-ink-2 ring-1 ring-line">
            {result.sql}
          </pre>
        )}
      </div>
    </Card>
  );
}

export function AskPage() {
  const { data: meta } = useMeta();
  const suggestions = useSuggestions();
  const ask = useAsk();
  const [question, setQuestion] = useState("");
  const [history, setHistory] = useState<AskResult[]>([]);
  const [error, setError] = useState<ApiError | Error | null>(null);

  const run = async (text: string) => {
    const q = text.trim();
    if (q.length < 3) return;
    setError(null);
    try {
      const result = await ask.mutateAsync(q);
      setHistory((h) => [result, ...h].slice(0, 10));
      setQuestion("");
    } catch (err) {
      setError(err instanceof Error ? err : new Error("Request failed"));
    }
  };

  const submit = (event: FormEvent) => {
    event.preventDefault();
    void run(question);
  };

  return (
    <>
      <PageHeader
        title="Ask"
        description="Questions about spend, vendors and exceptions, answered with read-only SQL over the reporting views."
      />

      <Card className="mb-4 p-4">
        <form onSubmit={submit} className="flex gap-2">
          <label htmlFor="question" className="sr-only">
            Question
          </label>
          <input
            id="question"
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
            placeholder={meta?.llm_enabled ? "e.g. Which vendors billed more than ₹5 L last quarter?" : "Pick a question below"}
            className="h-10 min-w-0 flex-1 rounded-lg border border-line-strong bg-surface px-3 text-sm text-ink placeholder:text-ink-3 focus:border-accent focus:ring-3 focus:ring-accent/20 focus:outline-none"
            maxLength={500}
          />
          <Button type="submit" variant="primary" loading={ask.isPending} className="h-10" icon={<ArrowUp className="size-4" />}>
            Ask
          </Button>
        </form>
        <div className="mt-3 flex flex-wrap gap-2">
          {suggestions.data?.questions.map((s) => (
            <button
              key={s}
              type="button"
              onClick={() => void run(s)}
              disabled={ask.isPending}
              className="rounded-full border border-line bg-surface-2 px-3 py-1 text-[12.5px] text-ink-2 transition-colors hover:border-line-strong hover:text-ink disabled:opacity-50"
            >
              {s}
            </button>
          ))}
        </div>
        <div className="mt-3 flex items-start gap-2 text-[12px] text-ink-3">
          <ShieldCheck className="mt-px size-3.5 shrink-0" aria-hidden />
          <span>
            {meta?.llm_enabled
              ? `Free-form questions are translated by ${meta.llm_model}.`
              : "No language model is configured, so curated questions are available."}{" "}
            Every query is parsed and checked: one SELECT, reporting views only, row-limited, read-only transaction.
          </span>
        </div>
      </Card>

      {error && (
        <Callout tone={error instanceof ApiError && error.status === 422 ? "warning" : "critical"} title={error.message} className="mb-4" />
      )}

      <div className="space-y-4">
        {history.map((result, i) => (
          <Answer key={`${history.length - i}-${result.question}`} result={result} />
        ))}
      </div>
    </>
  );
}
